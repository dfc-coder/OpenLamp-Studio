const fs=require('node:fs'),zlib=require('node:zlib'),crypto=require('node:crypto'),vm=require('node:vm'),path=require('node:path'),assert=require('node:assert/strict');
const root=path.join(__dirname,'..');
const parts=Array.from({length:19},(_,i)=>fs.readFileSync(path.join(root,'assets/shades/tallertop-original.olmesh.gz.part-'+String(i).padStart(2,'0'))));
const gz=Buffer.concat(parts);
assert.equal(crypto.createHash('sha256').update(gz).digest('hex'),'3c49c7f36ac77d74e74e4c624250540fa2e7f9305f908fd6eacbfd64b1421e7a');
const raw=zlib.gunzipSync(gz);
const context={window:{addEventListener(){}},console,Math,Float32Array,Uint32Array,ArrayBuffer,DataView,Map,Number,Error};
vm.runInNewContext(fs.readFileSync(path.join(root,'app.js'),'utf8'),context);
const api=context.window.OpenLampTest;
const buffer=raw.buffer.slice(raw.byteOffset,raw.byteOffset+raw.byteLength);
const mesh=api.parseStandMesh(buffer);
assert.equal(mesh.vertexCount,342396);assert.equal(mesh.triangleCount,684792);
assert(mesh.positions.every(Number.isFinite));
const stl=api.stlBinary(mesh);
assert.equal(stl.byteLength,84+50*684792);
assert.equal(new DataView(stl).getUint32(80,true),684792);
assert.equal(api.PRESETS.filter(p=>!p.archived).length,1);
assert.equal(api.PRESETS[0].id,'tallertop_original');
console.log('PASS: exact original OBJ mesh, 342396 vertices, 684792 faces, SHA-256 and binary STL.');
